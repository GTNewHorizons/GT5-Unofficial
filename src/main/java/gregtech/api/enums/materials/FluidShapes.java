package gregtech.api.enums.materials;

import java.util.Locale;
import java.util.function.Function;
import java.util.function.ObjIntConsumer;
import java.util.function.ToIntFunction;

import net.minecraftforge.fluids.Fluid;

import com.ruling_0.materiallib.api.FluidNamer;
import com.ruling_0.materiallib.api.Material;
import com.ruling_0.materiallib.api.MaterialLibAPI;
import com.ruling_0.materiallib.api.Property;
import com.ruling_0.materiallib.api.Shape;
import com.ruling_0.materiallib.api.StandardProperties;

import gregtech.api.enums.OrePrefixes;
import gregtech.api.material.FluidNames;
import gregtech.api.material.FluidRef;
import gregtech.api.material.GTMaterialProperties;

/// Fluid [Shape] declarations: liquid, gas, plasma and molten, plus the six cracked fluids.
///
/// A fluid listed in [MaterialFluidNames] registers under the Forge name and texture declared there, since world NBT
/// stores fluid stacks by name. Any other fluid takes MaterialLib's default name and the shape's default texture.
/// Temperatures come from the material's [GTMaterialProperties] (`LIQUID_TEMPERATURE` and its siblings).
public class FluidShapes {

    // spotless:off
    public static Shape fluidLiquid;
    public static Shape fluidGas;
    public static Shape fluidPlasma;
    public static Shape fluidMolten;
    public static Shape fluidHydroCracked1;
    public static Shape fluidHydroCracked2;
    public static Shape fluidHydroCracked3;
    public static Shape fluidSteamCracked1;
    public static Shape fluidSteamCracked2;
    public static Shape fluidSteamCracked3;
    // spotless:on

    static final String LIQUID_TEXTURE = "gregtech:fluids/fluid.autogenerated";
    static final String PLASMA_TEXTURE = "gregtech:fluids/fluid.plasma.autogenerated";
    static final String MOLTEN_TEXTURE = "gregtech:fluids/fluid.molten.autogenerated";

    public static void init() {
        fluidLiquid = fluidShape(
            "fluidLiquid",
            "%s",
            "gt.oreprefix.material",
            legacySlot(FluidNames::fluid),
            temperature(GTMaterialProperties.LIQUID_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::liquidAttrs);
        fluidGas = fluidShape(
            "fluidGas",
            "%s",
            "gt.oreprefix.material",
            legacySlot(FluidNames::gas),
            temperature(GTMaterialProperties.GAS_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
        fluidPlasma = fluidShape(
            "fluidPlasma",
            "%s Plasma",
            "gt.oreprefix.material_plasma",
            legacySlot(FluidNames::plasma),
            temperature(GTMaterialProperties.PLASMA_TEMPERATURE),
            PLASMA_TEXTURE,
            FluidShapes::plasmaAttrs);
        fluidMolten = fluidShape(
            "fluidMolten",
            "Molten %s",
            "gt.oreprefix.molten_material",
            legacySlot(FluidNames::molten),
            FluidShapes::moltenTemperature,
            MOLTEN_TEXTURE,
            FluidShapes::moltenAttrs);

        fluidHydroCracked1 = fluidShape(
            "fluidHydroCracked1",
            "Lightly Hydro-Cracked %s",
            "gt.oreprefix.lightly_hydro-cracked_material",
            crackedSlot("lightlyhydrocracked"),
            temperature(GTMaterialProperties.CRACKED_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
        fluidHydroCracked2 = fluidShape(
            "fluidHydroCracked2",
            "Moderately Hydro-Cracked %s",
            "gt.oreprefix.moderately_hydro-cracked_material",
            crackedSlot("moderatelyhydrocracked"),
            temperature(GTMaterialProperties.CRACKED_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
        fluidHydroCracked3 = fluidShape(
            "fluidHydroCracked3",
            "Severely Hydro-Cracked %s",
            "gt.oreprefix.severely_hydro-cracked_material",
            crackedSlot("severelyhydrocracked"),
            temperature(GTMaterialProperties.CRACKED_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
        fluidSteamCracked1 = fluidShape(
            "fluidSteamCracked1",
            "Lightly Steam-Cracked %s",
            "gt.oreprefix.lightly_steam-cracked_material",
            crackedSlot("lightlysteamcracked"),
            temperature(GTMaterialProperties.CRACKED_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
        fluidSteamCracked2 = fluidShape(
            "fluidSteamCracked2",
            "Moderately Steam-Cracked %s",
            "gt.oreprefix.moderately_steam-cracked_material",
            crackedSlot("moderatelysteamcracked"),
            temperature(GTMaterialProperties.CRACKED_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
        fluidSteamCracked3 = fluidShape(
            "fluidSteamCracked3",
            "Severely Steam-Cracked %s",
            "gt.oreprefix.severely_steam-cracked_material",
            crackedSlot("severelysteamcracked"),
            temperature(GTMaterialProperties.CRACKED_TEMPERATURE),
            LIQUID_TEXTURE,
            FluidShapes::gasAttrs);
    }

    private static Function<Material, FluidRef> legacySlot(Function<FluidNames, FluidRef> slot) {
        return material -> {
            FluidNames names = MaterialFluidNames.of(material.getName());
            return names == null ? null : slot.apply(names);
        };
    }

    /// A cracked fluid is named `prefix.<lowercase material name>` and drawn with its material's liquid or gas
    /// texture.
    private static Function<Material, FluidRef> crackedSlot(String prefix) {
        return material -> {
            FluidNames names = MaterialFluidNames.of(material.getName());
            FluidRef parent = names == null ? null : names.fluid() != null ? names.fluid() : names.gas();
            return new FluidRef(
                prefix + "."
                    + material.getName()
                        .toLowerCase(Locale.ENGLISH),
                parent != null ? parent.texture() : LIQUID_TEXTURE);
        };
    }

    private static Shape fluidShape(String name, String displayFormat, String displayFormatKey,
        Function<Material, FluidRef> ref, ToIntFunction<Material> temperature, String defaultTexture,
        ObjIntConsumer<Fluid> attrs) {
        return MaterialLibAPI.newFluidShape("gregtech", name)
            .displayName(displayFormat)
            .property(StandardProperties.DISPLAY_NAME_FORMAT_KEY, displayFormatKey)
            .property(StandardProperties.NAME_FORMATTER, OrePrefixes::shapeDisplayName)
            .fluidName((shape, material) -> {
                FluidRef fluidRef = ref.apply(material);
                return fluidRef != null ? fluidRef.name() : FluidNamer.DEFAULT.name(shape, material);
            })
            .configureFluid((material, fluid) -> {
                int kelvin = temperature.applyAsInt(material);
                fluid.setTemperature(kelvin);
                attrs.accept(fluid, kelvin);
                Integer luminosity = material.getProperty(GTMaterialProperties.FLUID_LUMINOSITY);
                if (luminosity != null) fluid.setLuminosity(luminosity);
            })
            .iconPath((shape, material) -> {
                FluidRef fluidRef = ref.apply(material);
                return fluidRef != null ? fluidRef.texture() : defaultTexture;
            })
            .build();
    }

    private static ToIntFunction<Material> temperature(Property<Integer> property) {
        return material -> material.getProperty(property);
    }

    private static int moltenTemperature(Material material) {
        int temperature = material.getProperty(GTMaterialProperties.MOLTEN_TEMPERATURE);
        if (temperature >= 0) return temperature;
        int meltingPoint = material.getProperty(GTMaterialProperties.MELTING_POINT);
        return meltingPoint >= 0 ? meltingPoint : 1000;
    }

    private static void liquidAttrs(Fluid fluid, int temperature) {
        fluid.setGaseous(false)
            .setViscosity(1000);
    }

    private static void gasAttrs(Fluid fluid, int temperature) {
        fluid.setGaseous(true)
            .setDensity(-100)
            .setViscosity(200);
    }

    private static void plasmaAttrs(Fluid fluid, int temperature) {
        fluid.setGaseous(true)
            .setDensity(55536)
            .setViscosity(10)
            .setLuminosity(15);
    }

    /// Mirrors the `MOLTEN` case of `GTFluid#configureFromStateTemperature`.
    private static void moltenAttrs(Fluid fluid, int temperature) {
        int luminosity = temperature >= 3500 ? 15 : (temperature < 1000 ? 0 : 14 * (temperature - 1000) / 2500 + 1);
        fluid.setGaseous(false)
            .setViscosity(1000)
            .setLuminosity(luminosity);
    }

    private FluidShapes() {}
}
