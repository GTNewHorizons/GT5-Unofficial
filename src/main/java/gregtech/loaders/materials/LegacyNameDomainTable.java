    /// Asserts every pinned material name still resolves to a registered MaterialLib material, so a stale
    /// row is a loud boot failure rather than a silent name-domain miss. Requires the resolved registry.
    public static void verifyResolvable() {
        int missing = 0;
        StringBuilder detail = new StringBuilder();
        for (Map.Entry<String, String> e : DOMAIN.entrySet()) {
            if (MaterialLibAPI.getMaterial("gregtech", e.getValue()) == null) {
                missing++;
                if (missing <= 20) detail.append(e.getKey())
                    .append("->")
                    .append(e.getValue())
                    .append(" ");
            }
        }
        if (missing > 0) {
            throw new IllegalStateException(
                "LegacyNameDomainTable: " + missing + " pinned names no longer resolve: " + detail);
        }
    }
